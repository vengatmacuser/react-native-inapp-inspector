#!/usr/bin/env node
/**
 * Build-time script: Reads GA4 credentials from .env, obfuscates them
 * with a keyed pseudorandom keystream, and writes the encrypted
 * payloads into src/constants/telemetryConfig.ts.
 *
 * The .env file and src/constants/telemetryConfig.ts are gitignored
 * (secrets never touch GitHub).
 */
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '..', '.env');
const envExists = fs.existsSync(envPath);

let measurementId = '';
let apiSecret = '';

if (envExists) {
  const envContent = fs.readFileSync(envPath, 'utf-8');
  const lines = envContent.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('#') || !trimmed.includes('=')) continue;
    const [key, ...valueParts] = trimmed.split('=');
    const value = valueParts.join('=').trim();
    if (key.trim() === 'GA4_MEASUREMENT_ID') measurementId = value;
    if (key.trim() === 'GA4_API_SECRET') apiSecret = value;
  }
}

const PKG_NAME = 'react-native-inapp-inspector';
const SALT = 'rn-inapp-inspector-telemetry-v1';
const KEY_MATERIAL = `${PKG_NAME}::${SALT}`;

function getKeystream(material, length) {
  const stream = [];
  let acc = 0x5a827999;
  for (let i = 0; i < length; i++) {
    const charCode = material.charCodeAt(i % material.length);
    acc = ((acc * 31 + charCode * 17 + i * 13) ^ (acc >>> 7)) & 0xffffffff;
    stream.push((acc >>> (i % 24)) & 0xff);
  }
  return stream;
}

function encrypt(text) {
  if (!text) return '';
  const keystream = getKeystream(KEY_MATERIAL, text.length);
  const out = [];
  for (let i = 0; i < text.length; i++) {
    const byte = text.charCodeAt(i);
    const k = keystream[i];
    const s = SALT.charCodeAt(i % SALT.length);
    const enc = (byte ^ k ^ s) & 0xff;
    out.push(('00' + enc.toString(16)).slice(-2));
  }
  return out.join('');
}

const outFile = path.join(__dirname, '..', 'src', 'constants', 'telemetryConfig.ts');

if (measurementId && apiSecret) {
  const encMid = encrypt(measurementId);
  const encSec = encrypt(apiSecret);

  const contents = [
    '// AUTO-GENERATED FILE — do not edit by hand.',
    '// Generated by scripts/gen-telemetry.js from .env at build time.',
    '',
    `export const ENC_MID = '${encMid}';`,
    `export const ENC_SEC = '${encSec}';`,
    `export const TELEMETRY_SALT = '${SALT}';`,
    '',
  ].join('\n');

  fs.writeFileSync(outFile, contents);
  console.log(`[gen-telemetry] Obfuscated GA4 credentials -> ${path.relative(process.cwd(), outFile)}`);
} else {
  const contents = [
    '// AUTO-GENERATED FILE — do not edit by hand.',
    'export const ENC_MID = \'\';',
    'export const ENC_SEC = \'\';',
    'export const TELEMETRY_SALT = \'\';',
    '',
  ].join('\n');

  fs.writeFileSync(outFile, contents);
  console.log(`[gen-telemetry] No .env credentials found — telemetry stub written`);
}
