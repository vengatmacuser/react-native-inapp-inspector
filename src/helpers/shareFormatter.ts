function safeStringify(data: any): string {
  if (data === undefined) return 'undefined';
  if (data === null) return 'null';
  if (typeof data === 'string') return data;
  try {
    return JSON.stringify(data, null, 2);
  } catch {
    return String(data);
  }
}

/**
 * Constructs a beautifully formatted markdown/text report for an API Network Log.
 */
export function formatApiReport(log: NetworkLog): string {
  const method = (log.method || 'GET').toUpperCase();
  const statusStr =
    log.status === 0
      ? 'Failed / Network Error'
      : log.status != null
      ? `${log.status} ${log.status === 200 ? 'OK' : ''}`.trim()
      : 'Pending';
  const durationStr = log.duration != null ? `${log.duration}ms` : 'N/A';
  const timeStr = formatDateTime(log.startTime || Date.now());
  const curlCmd = getCurlCommand(log);

  const lines: string[] = [
    '🚀 API INSPECTION REPORT',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `📌 Method:   ${method}`,
    `📊 Status:   ${statusStr}`,
    `⏱️ Duration: ${durationStr}`,
    `🕒 Time:     ${timeStr}`,
  ];

  if (log.client) {
    lines.push(`🔌 Client:   ${log.client.toUpperCase()}`);
  }

  lines.push(`🌐 URL:      ${log.url || 'N/A'}`);
  lines.push('');

  if (log.requestHeaders && Object.keys(log.requestHeaders).length > 0) {
    lines.push('📋 Request Headers:');
    lines.push(safeStringify(log.requestHeaders));
    lines.push('');
  }

  if (log.request != null && log.request !== '') {
    lines.push('📝 Request Body:');
    lines.push(safeStringify(log.request));
    lines.push('');
  }

  if (log.responseHeaders && Object.keys(log.responseHeaders).length > 0) {
    lines.push('📑 Response Headers:');
    lines.push(safeStringify(log.responseHeaders));
    lines.push('');
  }

  if (log.response != null && log.response !== '') {
    lines.push('📥 Response Data:');
    lines.push(safeStringify(log.response));
    lines.push('');
  }

  if (curlCmd) {
    lines.push('💻 cURL Command:');
    lines.push(curlCmd);
    lines.push('');
  }

  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  lines.push('Generated by React Native InApp Inspector');

  return lines.join('\n');
}

