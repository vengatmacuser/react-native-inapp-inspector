/**
 * Constructs a formatted report for a Crash Log.
 */
export function formatCrashReport(crash: CrashRecord): string {
  const timeStr = `${crash.dateStr || ''} ${crash.timeStr || ''}`.trim() || formatDateTime(crash.timestamp);
  const lines: string[] = [
    '💥 CRASH REPORT',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `⚠️ Error:   ${crash.name || 'Error'}: ${crash.message || 'Unknown error'}`,
    `🚨 Fatal:   ${crash.isFatal ? 'YES (Fatal)' : 'NO (Caught)'}`,
    `🏷️ Type:    ${(crash.type || 'js').toUpperCase()}`,
    `🕒 Time:    ${timeStr}`,
  ];

  if (crash.deviceInfo) {
    lines.push(`📱 Platform: ${crash.deviceInfo.platform || 'N/A'} (OS: ${crash.deviceInfo.osVersion || 'N/A'}, RN: ${crash.deviceInfo.rnVersion || 'N/A'})`);
  }
  if (crash.memoryInfo?.usedJSHeapSize) {
    lines.push(`💾 Used Heap: ${Math.round(crash.memoryInfo.usedJSHeapSize / (1024 * 1024))} MB`);
  }

  lines.push('');

  if (crash.stack) {
    lines.push('📜 Stack Trace:');
    lines.push(crash.stack);
    lines.push('');
  }

  if (crash.breadcrumbs && crash.breadcrumbs.length > 0) {
    lines.push(`🐾 Breadcrumbs (${crash.breadcrumbs.length}):`);
    crash.breadcrumbs.slice(-10).forEach(b => {
      lines.push(`  • [${b.type}] ${b.message} (${formatDateTime(b.timestamp)})`);
    });
    lines.push('');
  }

  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  lines.push('Generated by React Native InApp Inspector');

  return lines.join('\n');
}

