/**
 * Constructs a formatted report for a WebSocket / Socket.IO connection.
 */
export function formatSocketReport(record: SocketConnectionRecord): string {
  const clientStr = (record.client || 'websocket').toUpperCase();
  const statusStr = (record.status || 'open').toUpperCase();
  const durationStr = record.duration != null ? `${record.duration}ms` : 'Active / Open';
  const timeStr = formatDateTime(record.startTime || Date.now());

  const lines: string[] = [
    '🔌 WEBSOCKET / SOCKET.IO REPORT',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `📡 Client:       ${clientStr}`,
    `🌐 URL:          ${record.url || 'N/A'}`,
    `⚡ Status:       ${statusStr}`,
    `⏱️  Connected:    ${timeStr}`,
    `⏳ Duration:     ${durationStr}`,
    `📦 Total Frames: ${record.frames?.length || 0} (${record.sentCount || 0} sent, ${record.receivedCount || 0} recvd)`,
    `📊 Data Size:    ${(record.totalBytesSent || 0) + (record.totalBytesReceived || 0)} bytes`,
  ];

  if (record.protocols) {
    lines.push(`📜 Protocols:    ${Array.isArray(record.protocols) ? record.protocols.join(', ') : record.protocols}`);
  }
  if (record.closeCode != null) {
    lines.push(`🛑 Close Code:   ${record.closeCode} (${record.closeReason || 'N/A'})`);
  }
  if (record.error) {
    lines.push(`❌ Error:        ${record.error}`);
  }
  if (record.caller) {
    lines.push(`📍 Caller:       ${record.caller}`);
  }

  if (record.query && Object.keys(record.query).length > 0) {
    lines.push('');
    lines.push('🔍 Query Parameters:');
    lines.push(safeStringify(record.query));
  }

  if (record.frames && record.frames.length > 0) {
    lines.push('');
    lines.push('💬 Recent Message Frames:');
    record.frames.slice(-10).forEach((f, idx) => {
      const dirIcon = f.direction === 'send' ? '⬆️ SEND' : '⬇️ RECV';
      const eventTag = f.eventName ? ` [${f.eventName}]` : '';
      lines.push(`--- Frame #${idx + 1} (${dirIcon}${eventTag}, ${f.type}, ${f.size || 0}B) ---`);
      lines.push(safeStringify(f.data));
    });
  }

  lines.push('');
  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  lines.push('Generated by React Native InApp Inspector');

  return lines.join('\n');
}

